import AppKit
import SwiftUI

// The clipboard's page: the last things copied, newest first, each a click
// away from being on the clipboard again.
//
// The pasteboard says how many times it has changed; that number is looked
// at a little more than once a second, and only when it has moved is
// anything read. Kept in memory and nowhere else — quitting Resonata
// forgets it all — and what a password manager marks as secret is never
// taken. Off until switched on in Settings.

/// One thing that was copied.
struct Clip: Identifiable, Hashable {
    enum Content: Equatable {
        case text(String)
        /// An address: shown as a link.
        case link(String)
        /// A colour, "#E8875B": shown with its swatch.
        case colour(String)
        /// A picture: a small copy to show, and the data to put back.
        case image(NSImage, Data, NSPasteboard.PasteboardType)
        /// Files copied in Finder.
        case files([URL])
    }

    let id = UUID()
    var content: Content
    /// The app that was in front when it was copied.
    var app: String?
    var date: Date

    // One clip is one copying: told apart by that, not by what it holds.
    static func == (a: Clip, b: Clip) -> Bool { a.id == b.id }
    func hash(into hasher: inout Hasher) { hasher.combine(id) }
}

@MainActor
final class ClipboardStore: ObservableObject {

    static let shared = ClipboardStore()

    /// Newest first.
    @Published private(set) var clips: [Clip] = []
    /// The clip that is on the clipboard right now, if it is one of these.
    @Published private(set) var current: UUID?

    nonisolated static let limit = 20
    /// Pictures are kept whole, to be put back; only so many, and none huge.
    nonisolated static let pictureLimit = 6
    nonisolated static let pictureBytes = 12_000_000
    nonisolated static let textLength = 200_000

    private var timer: Timer?
    private var lastChange = 0

    func setEnabled(_ enabled: Bool) {
        if enabled, timer == nil {
            // What is on the clipboard when the page is switched on isn't
            // history yet: only what is copied from here on.
            lastChange = NSPasteboard.general.changeCount
            let timer = Timer(timeInterval: 0.75, repeats: true) { [weak self] _ in
                MainActor.assumeIsolated { self?.look() }
            }
            timer.tolerance = 0.25
            RunLoop.main.add(timer, forMode: .common)
            self.timer = timer
        } else if !enabled, timer != nil {
            timer?.invalidate()
            timer = nil
            clear()
        }
    }

    func clear() {
        clips = []
        current = nil
    }

    private func look() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = pasteboard.types ?? []
        guard !Self.isSecret(types.map(\.rawValue)), let content = Self.read(pasteboard, types: types) else {
            current = nil
            return
        }
        let front = NSWorkspace.shared.frontmostApplication
        let app = front?.bundleIdentifier == Bundle.main.bundleIdentifier ? nil : front?.localizedName
        take(Clip(content: content, app: app, date: Date()))
    }

    /// Adds a clip, for the page — or shows it again at the front if the
    /// same thing is already there.
    func take(_ clip: Clip) {
        clips = Self.adding(clip, to: clips)
        current = clips.first?.id
    }

    /// Puts a clip back on the clipboard, and at the front of the page.
    func copy(_ clip: Clip) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch clip.content {
        case .text(let text), .link(let text), .colour(let text):
            pasteboard.setString(text, forType: .string)
        case .image(_, let data, let type):
            pasteboard.setData(data, forType: type)
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        // Our own writing isn't a new copying.
        lastChange = pasteboard.changeCount
        var moved = clip
        moved.date = Date()
        clips = Self.adding(moved, to: clips.filter { $0.id != clip.id })
        current = clips.first?.id
    }

    // MARK: Pure parts

    /// What password managers and their like put beside something that
    /// shouldn't be kept: nspasteboard.org's markers.
    nonisolated static func isSecret(_ types: [String]) -> Bool {
        let marks: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                  "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        return types.contains(where: marks.contains)
    }

    /// What a copied string is: an address, a colour, or just text. Nil
    /// for nothing but blank space.
    nonisolated static func classify(_ string: String) -> Clip.Content? {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return nil }
        let text = String(string.prefix(textLength))
        if trimmed.range(of: "^#[0-9A-Fa-f]{6}$", options: .regularExpression) != nil {
            return .colour(trimmed.uppercased())
        }
        if trimmed.range(of: "^(https?://|www\\.)\\S+$", options: [.regularExpression, .caseInsensitive]) != nil {
            return .link(trimmed)
        }
        return .text(text)
    }

    /// `clips` with `clip` at the front: the same thing copied again moves
    /// up rather than appearing twice, and the oldest fall off the end.
    nonisolated static func adding(_ clip: Clip, to clips: [Clip]) -> [Clip] {
        var rest = clips.filter { !same($0.content, clip.content) }
        rest.insert(clip, at: 0)
        // Pictures hold their data: past the few newest, they go.
        var pictures = 0
        rest = rest.filter { item in
            guard case .image = item.content else { return true }
            pictures += 1
            return pictures <= pictureLimit
        }
        return Array(rest.prefix(limit))
    }

    nonisolated static func same(_ a: Clip.Content, _ b: Clip.Content) -> Bool {
        switch (a, b) {
        case (.text(let x), .text(let y)), (.link(let x), .link(let y)), (.colour(let x), .colour(let y)):
            x == y
        case (.files(let x), .files(let y)): x == y
        case (.image(_, let x, _), .image(_, let y, _)): x == y
        default: false
        }
    }

    /// "now", "4 min ago", "2 h ago" — and the day, from yesterday back.
    nonisolated static func age(of date: Date, now: Date) -> String {
        let seconds = now.timeIntervalSince(date)
        if seconds < 60 { return L.t("now", "teď") }
        let minutes = Int(seconds / 60)
        if minutes < 60 { return L.t("\(minutes) min ago", "před \(minutes) min") }
        let hours = minutes / 60
        if hours < 24 { return L.t("\(hours) h ago", "před \(hours) h") }
        return date.formatted(.dateTime.day().month(.abbreviated).locale(L.locale))
    }

    private static func read(_ pasteboard: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> Clip.Content? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self],
                                             options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let string = pasteboard.string(forType: .string), let content = classify(string) {
            return content
        }
        for type in [NSPasteboard.PasteboardType.png, .tiff] where types.contains(type) {
            guard let data = pasteboard.data(forType: type), data.count <= pictureBytes,
                  let image = NSImage(data: data), image.size.width > 0 else { continue }
            return .image(thumbnail(of: image), data, type)
        }
        return nil
    }

    /// A copy small enough to keep twenty of.
    private static func thumbnail(of image: NSImage) -> NSImage {
        let size = FileArrival.fitted(image.size, into: CGSize(width: 160, height: 160))
        let small = NSImage(size: size)
        small.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: size), from: .zero, operation: .copy, fraction: 1)
        small.unlockFocus()
        return small
    }
}

/// The open panel's "Schránka" page: a card for each thing copied.
struct ClipboardView: View {
    @ObservedObject var store: ClipboardStore
    /// The page's width, for how many cards fit in a row.
    var width: CGFloat

    private var columns: Int { width >= 560 ? 4 : 3 }
    private static let gap: CGFloat = 8
    private var cardWidth: CGFloat { (width - CGFloat(columns - 1) * Self.gap) / CGFloat(columns) }

    var body: some View {
        Group {
            if store.clips.isEmpty {
                empty
            } else {
                VStack(alignment: .leading, spacing: 6) {
                    ScrollView {
                        // The age is against the clock: twice a minute is as
                        // often as its minutes change.
                        TimelineView(.periodic(from: .now, by: 30)) { context in
                            EagerGrid(items: store.clips, columns: columns, spacing: Self.gap,
                                      rowSpacing: Self.gap) { clip in
                                ClipCard(clip: clip, current: store.current == clip.id, now: context.date,
                                         width: cardWidth) { store.copy(clip) }
                            }
                            .frame(maxWidth: .infinity, alignment: .leading)
                        }
                    }
                    .scrollIndicators(.never)
                    HStack {
                        Text(L.t("Click to copy again. Passwords from password managers are not kept.",
                                 "Klik zkopíruje znovu. Hesla ze správců hesel se neukládají."))
                            .font(.system(size: 10))
                            .foregroundStyle(.white.opacity(0.5))
                            .lineLimit(1)
                        Spacer()
                        Button(L.t("Clear", "Vyčistit")) { store.clear() }
                            .buttonStyle(.plain)
                            .font(.system(size: 11, weight: .semibold))
                            .foregroundStyle(.white.opacity(0.7))
                    }
                }
            }
        }
        .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
    }

    private var empty: some View {
        VStack(spacing: 8) {
            Image(systemName: "doc.on.clipboard")
                .font(.system(size: 26, weight: .medium))
            Text(L.t("Nothing copied yet", "Zatím nic zkopírovaného"))
                .font(.system(size: 13, weight: .semibold))
            Text(L.t("What you copy from now on shows up here.",
                     "Co odteď zkopíruješ, najdeš tady."))
                .font(.system(size: 11))
                .foregroundStyle(.white.opacity(0.5))
        }
        .foregroundStyle(.white.opacity(0.75))
        .frame(maxWidth: .infinity, maxHeight: .infinity)
    }
}

/// One card: what was copied, and from where and when under it.
private struct ClipCard: View {
    var clip: Clip
    /// It is what the clipboard holds right now.
    var current: Bool
    var now: Date
    var width: CGFloat
    var copy: () -> Void

    static let height: CGFloat = 54
    static let sky = ActivityLook.sky

    var body: some View {
        Button(action: copy) {
            VStack(alignment: .leading, spacing: 3) {
                what
                    .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
                HStack(spacing: 4) {
                    Text(meta)
                        .foregroundStyle(.white.opacity(current ? 0.78 : 0.6))
                    Spacer(minLength: 2)
                    if current {
                        Text(L.t("on clipboard", "ve schránce"))
                            .fontWeight(.bold)
                            .foregroundStyle(.white)
                            .fixedSize()
                    }
                }
                .font(.system(size: 8))
                .lineLimit(1)
            }
            .padding(.horizontal, 8)
            .padding(.vertical, 6)
            .frame(width: width, height: Self.height, alignment: .topLeading)
            .background(RoundedRectangle(cornerRadius: 9, style: .continuous)
                .fill(.white.opacity(current ? 0.12 : 0.06)))
            .overlay {
                if current {
                    RoundedRectangle(cornerRadius: 9, style: .continuous)
                        .strokeBorder(.white.opacity(0.4), lineWidth: 1)
                }
            }
            .contentShape(Rectangle())
        }
        .buttonStyle(TransportButtonStyle())
        .help(L.t("Copy again", "Zkopírovat znovu"))
        .accessibilityLabel(spoken)
        .accessibilityHint(L.t("Copies it again", "Zkopíruje to znovu"))
    }

    @ViewBuilder private var what: some View {
        switch clip.content {
        case .text(let text):
            Text(Self.shown(text))
                .font(.system(size: 9.5))
                .foregroundStyle(.white.opacity(0.92))
                .lineLimit(2)
                .multilineTextAlignment(.leading)
        case .link(let address):
            HStack(alignment: .top, spacing: 4) {
                Image(systemName: "link")
                    .font(.system(size: 9, weight: .bold))
                Text(Self.shortened(address))
                    .font(.system(size: 9.5))
                    .lineLimit(2)
                    .multilineTextAlignment(.leading)
            }
            .foregroundStyle(Self.sky)
        case .colour(let hex):
            HStack(spacing: 6) {
                RoundedRectangle(cornerRadius: 5, style: .continuous)
                    .fill(Color(hex: hex) ?? .white)
                    .frame(width: 20, height: 20)
                    .overlay(RoundedRectangle(cornerRadius: 5, style: .continuous)
                        .strokeBorder(.white.opacity(0.25), lineWidth: 0.5))
                Text(hex)
                    .font(.system(size: 10, design: .monospaced))
                    .foregroundStyle(.white.opacity(0.92))
            }
        case .image(let picture, _, _):
            HStack(spacing: 6) {
                let size = FileArrival.fitted(picture.size, into: CGSize(width: 44, height: 26))
                Image(nsImage: picture)
                    .resizable()
                    .frame(width: size.width, height: size.height)
                    .clipShape(RoundedRectangle(cornerRadius: 3, style: .continuous))
                Text(L.t("Picture", "Obrázek"))
                    .font(.system(size: 9.5, weight: .semibold))
                    .foregroundStyle(.white.opacity(0.92))
            }
        case .files(let urls):
            HStack(spacing: 5) {
                Image(nsImage: NSWorkspace.shared.icon(forFile: urls[0].path))
                    .resizable()
                    .frame(width: 22, height: 22)
                Text(urls.count == 1 ? urls[0].lastPathComponent
                                     : L.t("\(urls.count) files", "\(urls.count) soubory"))
                    .font(.system(size: 9.5))
                    .foregroundStyle(.white.opacity(0.92))
                    .lineLimit(2)
                    .truncationMode(.middle)
            }
        }
    }

    /// "Safari · 4 min ago", or just the age when the app isn't known.
    private var meta: String {
        [clip.app, ClipboardStore.age(of: clip.date, now: now)].compactMap { $0 }.joined(separator: " · ")
    }

    private var spoken: String {
        switch clip.content {
        case .text(let text): String(text.prefix(120))
        case .link(let address): address
        case .colour(let hex): L.t("Colour \(hex)", "Barva \(hex)")
        case .image: L.t("Picture", "Obrázek")
        case .files(let urls): urls.map(\.lastPathComponent).joined(separator: ", ")
        }
    }

    /// The text as the card shows it: its lines run together, so two lines
    /// of the card are two lines of words, not one and a blank.
    nonisolated static func shown(_ text: String) -> String {
        String(text.prefix(300)).split(whereSeparator: \.isNewline)
            .map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }.joined(separator: " ")
    }

    /// An address without its "https://": the part that tells them apart.
    nonisolated static func shortened(_ address: String) -> String {
        var short = address
        for prefix in ["https://", "http://", "www."] where short.lowercased().hasPrefix(prefix) {
            short.removeFirst(prefix.count)
        }
        return short
    }
}
